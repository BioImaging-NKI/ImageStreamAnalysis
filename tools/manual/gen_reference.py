"""The settings reference of the manual (manual/reference/settings.md), made from the program itself: the settings
dataclasses in config.py with their comments, and the labels of the import page (FIELDS in templates/gui.html).

    python tools/manual/gen_reference.py          (tests/test_manual.py fails when the page is stale)

Never edit the page by hand: change the comment in config.py or the label in gui.html, and run this again.
"""

from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CONFIG = ROOT / "src" / "imagestream_analysis" / "config.py"
GUI = ROOT / "src" / "imagestream_analysis" / "templates" / "gui.html"
OUT = ROOT / "manual" / "reference" / "settings.md"
SECTIONS = [("input", "InputSettings",
             "The input: the IDEAS export or the stack, the dataset, its channels and its pixel size."),
            ("channels", "ChannelSettings", "The role of each channel, given by channel number or by channel name."),
            ("segmentation", "SegmentationSettings", "Cellpose, and the clean-up of the cells it finds."),
            ("classification", "ClassificationSettings", "The thresholds of the subtype markers, artefacts and pools."),
            ("membrane", "MembraneSettings", "The membrane profiles and the enrichment at the interface.")]


def page_labels() -> dict[str, str]:
    """setting path -> its label on the import page"""
    text = GUI.read_text(encoding="utf-8")
    kinds = "choice|int|float|text|bool|list|pairs|thresholds"
    return {m[1]: m[2] for m in re.finditer(rf'\["(\w+\.\w+)", "([^"]+)", "(?:{kinds})"', text)}


def fields(source: str, cls: str) -> list[tuple[str, str, str]]:
    """(name, default, comment) of the fields of a dataclass, the comment from the lines above it and after it."""
    lines = source.splitlines()
    tree = ast.parse(source)
    node = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == cls)
    out = []
    for stmt in node.body:
        if not isinstance(stmt, ast.AnnAssign) or not isinstance(stmt.target, ast.Name):
            continue
        default = ast.get_source_segment(source, stmt.value) if stmt.value is not None else ""
        above = []
        k = stmt.lineno - 2
        while k >= 0 and lines[k].strip().startswith("#"):
            above.insert(0, lines[k].strip().lstrip("#").strip())
            k -= 1
        line = lines[stmt.lineno - 1]
        rest = line[stmt.end_col_offset :]  # an inline comment comes after the statement
        inline = rest.split("#", 1)[1].strip() if "#" in rest else ""
        comment = " ".join(c for c in [*above, inline] if c)
        out.append((stmt.target.id, default or "", comment))
    return out


def default_text(section: str, name: str) -> str:
    """The default as it is written in a settings file (from the program itself)."""
    from imagestream_analysis.config import Settings, _toml_value

    value = Settings().to_dict()[section][name]
    if value is None or value == "":
        return "(empty)"
    if value == {}:
        return "{}"
    if section == "input" and name in ("image", "output"):
        return _toml_value("" if value == "." else value) if value != "." else "(none)"
    return _toml_value(value)


def render() -> str:
    source = CONFIG.read_text(encoding="utf-8")
    labels = page_labels()
    parts = ["# All settings", "",
             "<!-- Generated by tools/manual/gen_reference.py from config.py and the import page: do not edit. -->", "",
             "This page lists every setting as it is written in a settings file or in `project.toml` "
             "(`[section]`, then `name = value`). For each setting it gives the default and, if the setting appears "
             "on the [import page](../guide/import-page.md), its label there. A channel can be given by its number "
             "or by its name.", ""]
    for section, cls, intro in SECTIONS:
        parts += [f"## `[{section}]`", "", intro, "", "| Setting | Default | On the import page | Meaning |",
                  "|---|---|---|---|"]
        for name, _, comment in fields(source, cls):
            label = labels.get(f"{section}.{name}", "")
            cell = comment.replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")
            default = default_text(section, name)
            parts.append(f"| `{name}` | {default if default.startswith('(') else f'`{default}`'} | {label} | {cell} |")
        parts.append("")
    return "\n".join(parts)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"{OUT}: {text.count(chr(10))} lines")
